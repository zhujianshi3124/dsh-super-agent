/** Route one decision as the foreman, answering its result; a refused one throws its reason. */
async function route(item: Record<string, unknown>): Promise<Record<string, unknown>> {
  const decision = item.kind === 'accept' && typeof item.proposal !== 'string' ? underInstruction(item) : item
  const { results } = await runTool(runtime.rotation.foremanSession(), 'orchestrator_route', { decisions: [decision] }) as { results: Record<string, unknown>[] }
  if (results[0]!.refused) throw new Error(String(results[0]!.refused))
  return results[0]!
}
/** The instruction each trigger and task of an accept got, so a second dispatch of one task stays one ticket (C-09). */
let instructions: Map<string, string>
/** The accept with an instruction this test approved for its trigger and task (C-22). */
function underInstruction(item: Record<string, unknown>): Record<string, unknown> {
  const task = typeof item.task === 'number' ? item.task : 1
  const key = `${String(item.trigger_id)}:${task}`
  let proposal = instructions.get(key)
  if (!proposal) {
    const titled = String(item.title ?? 'Test work')
    proposal = runtime.proposals.approve(runtime.proposals.draft({ tasks: [{ title: titled, request: titled, accept: titled }], heard: titled }).id).id
    instructions.set(key, proposal)
  }
  return { ...item, proposal, task }
}
